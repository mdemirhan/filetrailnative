// Writes Sources/FTFoundation/Design/ThemePalette.swift from Tests/Golden/css-tokens.json: the
// theme-dependent colours, shadows and the pressed-button brightness. The Swift test still
// compares every property against the golden independently.
//   bun tools/tokens/extract-css.ts && bun tools/tokens/gen-swift-palette.ts && xcrun swift-format format -i Sources/FTFoundation/Design/ThemePalette.swift
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO_ROOT, parseColor, splitTopLevel } from "./lib";

type Token = { raw: string; value?: string; unresolved?: true };
const golden = (await Bun.file(join(REPO_ROOT, "Tests/Golden/css-tokens.json")).json()) as {
  light: Record<string, Token>;
  dark: Record<string, Token>;
};

// Derived from the accent at run time: AccentPalette owns them.
const ACCENT_DERIVED = new Set([
  "--batch-rename-mark-bg",
  "--batch-rename-mark-text",
  "--bg-active",
  "--crumb-active-bg",
  "--field-focus",
  "--focus-ring",
  "--get-info-action-bg-hover",
  "--get-info-action-icon-hover",
  "--get-info-action-text-hover",
  "--get-info-hero-icon-bg",
  "--search-border-active",
  "--search-caret",
  "--search-icon-active",
  "--search-shadow-active",
]);

function camel(name: string): string {
  return name
    .replace(/^--/u, "")
    .replace(/-([a-z0-9])/gu, (_, ch: string) => ch.toUpperCase());
}

function num(text: string): string {
  return text.includes(".") || text.includes("e") ? text : `${text}`;
}

function colorLiteral(text: string): string {
  const c = parseColor(text);
  if (!c) throw new Error(`not a colour: ${text}`);
  const alpha = c.a === 1 ? "" : `, alpha: ${num(String(c.a))}`;
  return `RGBA(r: ${c.r}, g: ${c.g}, b: ${c.b}${alpha})`;
}

function length(text: string): string {
  return text === "0" ? "0" : text.replace(/px$/u, "");
}

function shadowLiteral(text: string): string {
  if (text === "none") return "[]";
  const layers = splitTopLevel(text).map((layer) => {
    const inset = layer.startsWith("inset ");
    const body = inset ? layer.slice("inset ".length) : layer;
    const color = /(rgba?\([^)]*\)|#[0-9a-f]{6})$/u.exec(body);
    if (!color) throw new Error(`no colour in shadow: ${text}`);
    const lengths = body.slice(0, color.index).trim().split(/\s+/u).map(length);
    const [x, y, blur, spread] = lengths;
    const args = [
      ...(inset ? ["inset: true"] : []),
      `x: ${x}`,
      `y: ${y}`,
      `blur: ${blur}`,
      ...(spread ? [`spread: ${spread}`] : []),
      `color: ${colorLiteral(color[1])}`,
    ];
    return `ShadowLayer(${args.join(", ")})`;
  });
  return `[${layers.join(", ")}]`;
}

type Kind = "color" | "shadow" | "brightness";

function classify(value: string): Kind | null {
  if (value === "none" || /^(inset )?[\d.]+(px)? /u.test(value) || /^0 /u.test(value)) return "shadow";
  if (/^brightness\(/u.test(value)) return "brightness";
  if (parseColor(value)) return "color";
  return null;
}

const names = Object.keys(golden.light).filter((name) => {
  if (ACCENT_DERIVED.has(name)) return false;
  if (name.startsWith("--ft-accent-")) return false;
  const value = golden.light[name].value ?? "";
  return classify(value) !== null;
});

const swiftType: Record<Kind, string> = {
  color: "RGBA",
  shadow: "[ShadowLayer]",
  brightness: "Double",
};

const kinds = names.map((name) => classify(golden.light[name].value as string) as Kind);

function literal(theme: "light" | "dark"): string {
  const args = names.map((name, index) => {
    const value = golden[theme][name].value as string;
    const kind = kinds[index];
    const swift =
      kind === "color"
        ? colorLiteral(value)
        : kind === "shadow"
          ? shadowLiteral(value)
          : /brightness\(([\d.]+)\)/u.exec(value)?.[1];
    return `        ${camel(name)}: ${swift}`;
  });
  return `ThemePalette(\n${args.join(",\n")}\n    )`;
}

const properties = names
  .map((name, index) => `    /// \`${name}\`\n    public let ${camel(name)}: ${swiftType[kinds[index]]}`)
  .join("\n\n");

const source = `// Generated by tools/tokens/gen-swift-palette.ts from Tests/Golden/css-tokens.json; do not edit.
// Port of the light and dark blocks of apps/desktop/src/renderer/styles.css

/// Every theme-dependent colour and shadow of the reference stylesheet. Tokens that follow the
/// accent colour live in \`AccentPalette\`.
public struct ThemePalette: Equatable, Sendable {
${properties}

    public static let light = ${literal("light")}

    public static let dark = ${literal("dark")}

    public static func palette(for appearance: ThemeAppearance) -> ThemePalette {
        switch appearance {
        case .light: light
        case .dark: dark
        }
    }
}
`;

writeFileSync(join(REPO_ROOT, "Sources/FTFoundation/Design/ThemePalette.swift"), source);
