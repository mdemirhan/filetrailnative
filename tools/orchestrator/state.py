#!/usr/bin/env python3
"""Reads and updates the port's orchestrator state (docs/port/state/orchestrator.json).

Every change also appends a line to journal.jsonl, so a half-written state can be
rebuilt. Standard library only.

Usage:
  state.py show
  state.py batch-args <batchId>            # JSON args for tools/orchestrator/workflows/batch.js
  state.py set-batch <batchId> <status> [--run-id ID]
  state.py add-batch <batchId> <wpId>...   # plan a batch
  state.py apply-report <report.json>      # the workflow's return value, saved to a file
  state.py meter <weeklyPct> <fiveHourPct> [note]
  state.py pause <reason> [--until ISO] | unpause
  state.py next <text>                     # set nextAction
  state.py status-md                       # rewrite docs/port/STATUS.md
"""

from __future__ import annotations

import datetime as dt
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
STATE_DIR = ROOT / "docs/port/state"
STATE = STATE_DIR / "orchestrator.json"
JOURNAL = STATE_DIR / "journal.jsonl"
PREAMBLE = STATE_DIR / "preamble.md"
STATUS_MD = ROOT / "docs/port/STATUS.md"

WP_STATUSES = [
    "todo",
    "implementing",
    "implemented",
    "gated",
    "reviewed",
    "fixing",
    "ready",
    "merged",
    "blocked",
]
# Agent-run estimates per WP, used to keep a batch under the workflow-size guideline.
RISK_WEIGHT = {"low": 2, "medium": 5, "high": 7}


def now() -> str:
    return dt.datetime.now(dt.UTC).isoformat(timespec="seconds")


def load() -> dict[str, Any]:
    return json.loads(STATE.read_text())


def save(state: dict[str, Any], event: str, **detail) -> None:
    state["updatedAt"] = now()
    tmp = STATE.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(state, indent=2, ensure_ascii=False) + "\n")
    tmp.replace(STATE)
    with JOURNAL.open("a") as journal:
        journal.write(
            json.dumps(
                {"at": state["updatedAt"], "event": event, **detail}, ensure_ascii=False
            )
            + "\n"
        )


def batch_args(state: dict[str, Any], batch_id: str) -> dict[str, Any]:
    batch = state["batches"][batch_id]
    wps = []
    for wp_id in batch["wps"]:
        wp = state["wps"][wp_id]
        brief = (STATE_DIR / "wp" / f"{wp_id}.md").read_text()
        wps.append(
            {
                "id": wp_id,
                "title": wp["title"],
                "risk": wp["risk"],
                "model": wp["model"],
                "lenses": wp.get("lenses", []),
                "gate": wp.get("gate", []),
                "brief": brief,
            }
        )
    return {
        "batchId": batch_id,
        "repo": str(ROOT),
        "preamble": PREAMBLE.read_text(),
        "integrate": batch.get("integrate", True),
        "critic": batch.get("critic"),
        "wps": wps,
    }


def apply_report(state: dict[str, Any], report: dict[str, Any]) -> list[str]:
    changed = []
    for wp_report in report.get("reports", []):
        if not wp_report:
            continue
        wp = state["wps"][wp_report["id"]]
        wp["status"] = wp_report.get("status", wp["status"])
        for key in (
            "headSha",
            "summary",
            "gate",
            "findings",
            "fixes",
            "sharedFileRequests",
            "deviations",
            "blockers",
        ):
            if key in wp_report and wp_report[key] is not None:
                wp[key] = wp_report[key]
        wp["attempts"] = wp.get("attempts", 0) + 1
        changed.append(wp_report["id"])
    integration = report.get("integration") or {}
    for wp_id in integration.get("merged", []):
        state["wps"][wp_id]["status"] = "merged"
    for item in integration.get("notMerged", []):
        wp = state["wps"].get(item.get("wp", ""))
        if wp:
            wp.setdefault("blockers", []).append(f"merge: {item.get('reason', '')}")
    batch = state["batches"].get(report.get("batchId", ""))
    if batch:
        batch["status"] = "done"
        batch["endedAt"] = now()
        batch["integration"] = integration
        batch["critic"] = report.get("critic")
        batch["spentOutputTokens"] = report.get("spentOutputTokens")
    return changed


def status_md(state: dict[str, Any]) -> str:
    lines = [
        "# Port status",
        "",
        f"Updated {state.get('updatedAt', '')}. Generated by `tools/orchestrator/state.py status-md`.",
        "",
    ]
    pause = state["pause"]
    lines += [
        f"- **Wave / phase:** {state['wave']} / {state['phase']}",
        f"- **Next action:** {state.get('nextAction', '')}",
        f"- **Paused:** {'yes — ' + str(pause['reason']) + (' until ' + pause['until'] if pause.get('until') else '') if pause['requested'] else 'no'}",
    ]
    if state["meter"]:
        last = state["meter"][-1]
        lines.append(
            f"- **Usage meter:** weekly {last['weeklyPct']}%, 5-hour {last['fiveHourPct']}% ({last['at']})"
        )
    lines += [
        "",
        "## Work packages",
        "",
        "| WP | Title | Risk · model | Status | Summary |",
        "|---|---|---|---|---|",
    ]
    for wp_id, wp in state["wps"].items():
        summary = (wp.get("summary") or "").replace("\n", " ").replace("|", "\\|")[:160]
        lines.append(
            f"| {wp_id} | {wp['title']} | {wp['risk']} · {wp['model']} | {wp['status']} | {summary} |"
        )
    lines += [
        "",
        "## Batches",
        "",
        "| Batch | WPs | Status | Run id |",
        "|---|---|---|---|",
    ]
    for batch_id, batch in state["batches"].items():
        lines.append(
            f"| {batch_id} | {', '.join(batch['wps'])} | {batch['status']} | {batch.get('runId') or ''} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__)
        return 2
    command, rest = argv[0], argv[1:]
    state = load()
    if command == "show":
        print(json.dumps(state, indent=2, ensure_ascii=False))
    elif command == "batch-args":
        print(json.dumps(batch_args(state, rest[0]), ensure_ascii=False))
    elif command == "add-batch":
        batch_id, wp_ids = rest[0], rest[1:]
        weight = sum(RISK_WEIGHT[state["wps"][w]["risk"]] for w in wp_ids) + 1
        state["batches"][batch_id] = {
            "wps": wp_ids,
            "status": "planned",
            "runId": None,
            "estimatedAgents": weight,
        }
        save(state, "add-batch", batch=batch_id, wps=wp_ids, estimatedAgents=weight)
        print(f"{batch_id}: ~{weight} agents")
    elif command == "set-batch":
        batch = state["batches"][rest[0]]
        batch["status"] = rest[1]
        if "--run-id" in rest:
            batch["runId"] = rest[rest.index("--run-id") + 1]
        if rest[1] == "running":
            batch["startedAt"] = now()
            for wp_id in batch["wps"]:
                if state["wps"][wp_id]["status"] == "todo":
                    state["wps"][wp_id]["status"] = "implementing"
        save(
            state, "set-batch", batch=rest[0], status=rest[1], runId=batch.get("runId")
        )
    elif command == "apply-report":
        report = json.loads(Path(rest[0]).read_text())
        changed = apply_report(state, report)
        save(state, "apply-report", batch=report.get("batchId"), wps=changed)
        print("updated: " + ", ".join(changed))
    elif command == "meter":
        entry = {
            "at": now(),
            "weeklyPct": float(rest[0]),
            "fiveHourPct": float(rest[1]),
            "note": " ".join(rest[2:]),
        }
        state["meter"].append(entry)
        save(state, "meter", **entry)
    elif command == "pause":
        until = rest[rest.index("--until") + 1] if "--until" in rest else None
        reason = " ".join(r for r in rest if r != "--until" and r != until)
        state["pause"] = {"requested": True, "reason": reason, "until": until}
        save(state, "pause", reason=reason, until=until)
    elif command == "unpause":
        state["pause"] = {"requested": False, "reason": None, "until": None}
        save(state, "unpause")
    elif command == "next":
        state["nextAction"] = " ".join(rest)
        save(state, "next", text=state["nextAction"])
    elif command == "status-md":
        STATUS_MD.write_text(status_md(state))
        print(f"wrote {STATUS_MD.relative_to(ROOT)}")
    else:
        print(f"unknown command {command}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
