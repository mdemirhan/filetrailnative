// Writes Sources/FTFileSystem/Listing/CollationTable.swift: which non-ASCII characters the reference's name
// comparison (a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }), used by compareEntriesByName
// in packages/core/src/fs/explorerService.ts) takes for ASCII ones, so names with accents can be compared by
// bytes like plain ones. A character is
//   - ignorable when it compares equal to "" (the combining accents of a decomposed name, say), or
//   - the same as one ASCII character or letter pair when it compares equal to it ("é" is "e", "ß" is "ss").
// Characters that are neither (Cyrillic, CJK, emoji…) are left out: a name with one is compared as text.
//
// Usage: bun tools/parity/collation-table.ts          (writes the file)
//        bun tools/parity/collation-table.ts --check  (fails if the file would change)
// The listing-sort golden tests the table: its names are full of accents.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { REPO_ROOT } from "./lib/reference";

const OUTPUT = join(REPO_ROOT, "Sources/FTFileSystem/Listing/CollationTable.swift");

const compare = (left: string, right: string): number =>
  left.localeCompare(right, undefined, { numeric: true, sensitivity: "base" });

// The scalars looked at: Latin-1 Supplement to Latin Extended-B, Latin Extended Additional, combining marks,
// and the general punctuation (curly quotes, dashes, spaces).
const RANGES: Array<[number, number]> = [
  [0x00a0, 0x024f],
  [0x0300, 0x036f],
  [0x1e00, 0x1eff],
  [0x2000, 0x206f],
  // The ligatures "ﬁ" and "ﬂ", and the fullwidth forms of ASCII letters and signs.
  [0xfb00, 0xfb06],
  [0xff01, 0xff5e],
];

const asciiCandidates: string[] = [];
for (let code = 0x09; code <= 0x7e; code++) {
  const character = String.fromCharCode(code);
  // Digits are numbers to the comparison, and nothing else is taken for one.
  if (code >= 0x30 && code <= 0x39) {
    continue;
  }
  // Letters are taken as their lowercase.
  if (code >= 0x41 && code <= 0x5a) {
    continue;
  }
  if (compare(character, "") !== 0) {
    asciiCandidates.push(character);
  }
}
const letters = "abcdefghijklmnopqrstuvwxyz".split("");
const pairs = letters.flatMap((first) => letters.map((second) => first + second));
const candidates = [...asciiCandidates, ...pairs];

const ignorable: number[] = [];
const replacements = new Map<number, string>();
for (const [first, last] of RANGES) {
  for (let code = first; code <= last; code++) {
    const character = String.fromCodePoint(code);
    if (compare(character, "") === 0) {
      ignorable.push(code);
      continue;
    }
    // A character that compares equal to a letter must do so beside any other: the pairs "dz" and the like
    // are looked at the same way.
    const found = candidates.find((candidate) => compare(character, candidate) === 0);
    if (found !== undefined && !/^[0-9]/.test(found)) {
      replacements.set(code, found);
    }
  }
}

const hex = (code: number) => `0x${code.toString(16).toUpperCase().padStart(4, "0")}`;
const lines: string[] = [];
lines.push("// Generated by tools/parity/collation-table.ts from the reference's localeCompare. Do not edit.");
lines.push("");
lines.push("/// How the reference's name comparison (numeric, base sensitivity) takes non-ASCII characters.");
lines.push("enum CollationTable {");
lines.push("    /// Characters the comparison ignores: the combining accents of a decomposed name, and the like.");
lines.push("    static let ignorable: Set<UInt32> = [");
for (let index = 0; index < ignorable.length; index += 8) {
  lines.push(`        ${ignorable.slice(index, index + 8).map(hex).join(", ")},`);
}
lines.push("    ]");
lines.push("");
lines.push("    /// Characters that compare equal to ASCII ones: the lowercase letters, letter pair or punctuation.");
lines.push("    static let replacements: [UInt32: StaticString] = [");
for (const [code, replacement] of replacements) {
  lines.push(`        ${hex(code)}: ${JSON.stringify(replacement)},`);
}
lines.push("    ]");
lines.push("}");
const text = `${lines.join("\n")}\n`;

if (process.argv.includes("--check")) {
  if (readFileSync(OUTPUT, "utf8") !== text) {
    console.error("CollationTable.swift is out of date: run bun tools/parity/collation-table.ts");
    process.exit(1);
  }
  console.log("CollationTable.swift is up to date");
} else {
  writeFileSync(OUTPUT, text);
  console.log(`${ignorable.length} ignorable, ${replacements.size} replacements`);
}
