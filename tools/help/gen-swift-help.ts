// Writes Sources/FTFoundation/Help/HelpTopics.swift from the reference's lib/helpContent.ts (HELP_TOPICS and
// SHORTCUT_ITEMS), without the zoom rows (DEVIATIONS D-005).
// Usage: bun tools/help/gen-swift-help.ts [--check]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { REPO_ROOT, importReference } from "../parity/lib/reference";
import { withoutZoom } from "./without-zoom";

const OUT = join(REPO_ROOT, "Sources/FTFoundation/Help/HelpTopics.swift");

type Row = { label: string; code?: boolean; description: string };
type Section = { title: string; rows: Row[]; note?: string };
type Topic = { id: string; title: string; intro: string; sections: Section[] };
type Item = { group: string; description: string; shortcut?: string; command?: string };

function swiftString(text: string): string {
  let out = '"';
  for (const ch of text) {
    const code = ch.codePointAt(0) ?? 0;
    if (ch === '"') out += '\\"';
    else if (ch === "\\") out += "\\\\";
    else if (ch === "\n") out += "\\n";
    else if (code < 0x20 || code === 0x7f) out += `\\u{${code.toString(16)}}`;
    else out += ch;
  }
  return `${out}"`;
}

const module = await importReference<{ HELP_TOPICS: Topic[]; SHORTCUT_ITEMS: Item[] }>(
  "apps/desktop/src/renderer/lib/helpContent.ts",
);
const { topics, items } = withoutZoom(module.HELP_TOPICS, module.SHORTCUT_ITEMS);

const lines: string[] = [];
lines.push(
  "// Generated by tools/help/gen-swift-help.ts from HELP_TOPICS and SHORTCUT_ITEMS in apps/desktop/src/renderer/lib/helpContent.ts; do not edit.",
  "// The Zoom In, Zoom Out and Actual Size rows and the Zoom row of Appearance are left out (DEVIATIONS D-005).",
  "",
  "extension HelpContent {",
  "    public static let topics: [HelpTopic] = [",
);
for (const topic of topics) {
  lines.push("        HelpTopic(", `            id: .${topic.id}, title: ${swiftString(topic.title)},`);
  lines.push(`            intro: ${swiftString(topic.intro)},`);
  if (topic.sections.length === 0) {
    lines.push("            sections: []),");
    continue;
  }
  lines.push("            sections: [");
  for (const section of topic.sections) {
    lines.push("                HelpSection(", `                    title: ${swiftString(section.title)},`, "                    rows: [");
    for (const row of section.rows) {
      const code = row.code ? ", code: true" : "";
      lines.push(`                        HelpRow(label: ${swiftString(row.label)}${code},`);
      lines.push(`                            description: ${swiftString(row.description)}),`);
    }
    lines.push(section.note === undefined ? "                    ])," : `                    ], note: ${swiftString(section.note)}),`);
  }
  lines.push("            ]),");
}
lines.push("    ]", "", "    static let shortcutItems: [HelpShortcutItem] = [");
for (const item of items) {
  const source = item.command !== undefined ? `.command(.${item.command})` : `.fixed(${swiftString(item.shortcut ?? "")})`;
  lines.push(`        HelpShortcutItem(group: .${item.group}, ${source}, ${swiftString(item.description)}),`);
}
lines.push("    ]", "}", "");
// Written as swift-format writes it, so the file passes the lint in scripts/ci.sh.
const raw = lines.join("\n");
const formatted = Bun.spawnSync(["xcrun", "swift-format", "format"], { stdin: new TextEncoder().encode(raw) });
if (formatted.exitCode !== 0) {
  console.error(`swift-format failed: ${formatted.stderr.toString()}`);
  process.exit(1);
}
const text = formatted.stdout.toString();

if (process.argv.includes("--check")) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) {
    console.error("HelpTopics.swift is out of date: run bun tools/help/gen-swift-help.ts");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${topics.length} topics, ${items.length} shortcut rows)`);
}
